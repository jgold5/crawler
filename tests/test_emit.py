def test_suggestions():
    cfg = SiteConfig(test_id_attrs=["data-qa"])
    s = suggestion(R(page="P", name="okBtn", xpath="//div[@aria-label='Confirm']//button[2]", tag="button",
                     fragile=True), cfg)
    assert s == "ask devs to add `data-qa` to the `<button>` used as `okBtn` in section 'Confirm' on page P"
    s = suggestion(R(page="P", name="x", xpath="(//input[@placeholder='Search'])[3]", fragile=True), cfg)
    assert "the `<input>` 'Search'" in s or "Search" in s
    assert "getRowId" in suggestion(grid_result(fragile=True), cfg)


