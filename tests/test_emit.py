    tpl = LocatorTemplate("{rowKey}|{class}|{rowKeyX}{missing}", ["rowKey", "class", "rowKeyX"], {})
    files = gen(tmp_path, [R(page="P", name="cell", template=tpl, kind="grid-cell")], helper_package="com.example.support")
