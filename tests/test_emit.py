GRID_TPL = ("//div[@role='row' and @row-id=//div[@col-id='orderId' and normalize-space()={orderId}]"
            "/../@row-id]//div[@col-id='qty']")


def R(page="Login", name="emailInput", xpath="//input[@name='email']", strategy="name", score=90.0, **kw):
    kw.setdefault("runs_verified", 2)
    return LocatorResult(page=page, name=name, xpath=xpath, strategy=strategy, score=score, **kw)


def grid_result(**kw):
    return R(page="Orders", name="quantityCell", strategy="grid-cell", score=80, kind="grid-cell", tag="div",
             xpath=emit.fill_template(GRID_TPL, ["orderId"], {"orderId": "A-100"}),
             template=LocatorTemplate(GRID_TPL, ["orderId"], {"orderId": "A-100"}), **kw)


def sample():
    return [
        R(),
        R(name="passwordInput", xpath="//input[@type='password']", strategy="label", score=70, tag="input",
          sources=["login.feature:5", "login.feature:4"]),
        R(page="Settings", name="saveButton", strategy="positional", score=20, tag="button", fragile=True,
          xpath="//section[.//h2='Security']//button[normalize-space()='Save'][2]",
          notes=["positional index [2]"], runs_verified=1,
          fallbacks=[Candidate("//form[*/h2]//button[2]", "anchored", 30.5)]),
        grid_result(),
    ]


def cfg_with(**java) -> SiteConfig:
    return SiteConfig(java=JavaDef(**java))


def gen(tmp_path, results=None, **java) -> dict[str, str]:
    cfg = cfg_with(**java)
    paths = write_all(sample() if results is None else results, cfg, tmp_path)
    return {p.relative_to(tmp_path).as_posix(): p.read_text(encoding="utf-8") for p in paths}


def page_src(files, cls, pkg="com/example/pages"):
    return files[f"java/{pkg}/{cls}.java"]


# ---------------------------------------------------------------- escaping primitives

@pytest.mark.parametrize("value, lit", [
    ("abc", "'abc'"),
    ("it's", '"it\'s"'),
    ('say "hi"', "'say \"hi\"'"),
    ("it's \"x\"", "concat('it', \"'\", 's \"x\"')"),
    ("'\"", "concat(\"'\", '\"')"),
    ("\"'", "concat('\"', \"'\")"),
    ("a''\"b", "concat('a', \"'\", \"'\", '\"b')"),
    ("", "''"),
])
def test_xpath_literal(value, lit):
    assert xpath_literal(value) == lit


def test_java_string_escaping():
    assert jv.java_string('a"b\\c') == '"a\\"b\\\\c"'
    assert jv.java_string("l1\nl2\r\t") == '"l1\\nl2\\r\\t"'
    assert jv.java_string("Grüße – 日本") == '"Grüße – 日本"'  # non-ASCII kept
    assert jv.java_string("C:\\users") == '"C:\\\\users"'      # no accidental \u escape
    assert jv.java_string("\x01") == '"\\u0001"'


def test_javadoc_escaping():
    s = jv.javadoc_text("//div[*/h2]/*x*/ @id <b> & {@link X} C:\\users\nnext")
    assert "*/" not in s and "/*" not in s
    assert "@" not in s and "<" not in s and ">" not in s and "\\" not in s and "\n" not in s
    assert "&amp;" in s and "&#64;id" in s


def test_naming():
    assert naming.upper_snake("emailInput") == "EMAIL_INPUT"
    assert naming.upper_snake("URLField2") == "URL_FIELD_2"
    assert naming.camel("Order ID") == "orderId"
    assert naming.camel("save-btn") == "saveBtn"
    assert naming.camel("class") == "class_"
    assert naming.camel("2fa code") == "_2faCode"
    assert naming.camel("") == "element"
    assert naming.camel("Größe") == "grosse" or naming.camel("Größe").isascii()
    assert naming.class_name("Login", "Page") == "LoginPage"
    assert naming.class_name("orders page", "Page") == "OrdersPage"
    assert naming.class_name("my-account", "Screen") == "MyAccountScreen"
    assert naming.class_name("Login", "") == "Login"


