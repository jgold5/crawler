def test_report(tmp_path):
    rep = gen(tmp_path)["report.md"]
    assert rep.startswith("<!-- Generated by crawler. DO NOT EDIT BY HAND.")
    assert "| Locators | 4 |" in rep and "| Fragile | 1 |" in rep and "| Grid templates | 1 |" in rep
    assert "| Single-run only | 1 |" in rep and "| Unverified (0 runs) | 0 |" in rep
    assert re.search(r"\| Median XPath length \| \d+(\.\d+)? \|", rep)
    assert "| positional | 1 |" in rep
    attn = rep.split("## Needs attention")[1].split("## Pages")[0]
    assert "Settings.saveButton" in attn and "positional index \\[2\\]" in attn
    assert "ask devs to add `data-testid` to the `<button>` 'Save' in section 'Security'" in attn
    pages = rep.split("## Pages")[1]
    assert pages.index("### Login") < pages.index("### Orders") < pages.index("### Settings")
    assert "| quantityCell(orderId) | `" + GRID_TPL + "` | grid-cell | 80 |" in pages
    assert "| saveButton (fragile) |" in pages


