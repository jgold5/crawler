# ---------------------------------------------------------------- escaping in output

def test_escaping_in_generated_java(tmp_path):
    rs = [R(page="Esc", name="both", xpath="//b[.=concat('it', \"'\", 's \"x\"')]"),
          R(page="Esc", name="slash", xpath="//td[.='C:\\users\\new']"),
          R(page="Esc", name="star", xpath="//section[*/h2='Größe']//button", notes=["see */ and @here"],
            fallbacks=[Candidate("//*/h2/*", "anchored", 1)]),
          R(page="Esc", name="uni", xpath="//button[.='保存 ✓']")]
    src = page_src(gen(tmp_path, rs), "EscPage")
    assert 'By.xpath("//b[.=concat(\'it\', \\"\'\\", \'s \\"x\\"\')]")' in src
    assert 'By.xpath("//td[.=\'C:\\\\users\\\\new\']")' in src
    assert "By.xpath(\"//button[.='保存 ✓']\")" in src
    # no comment terminators inside javadoc, no raw \u
    for m in re.finditer(r"/\*\*(.*?)\*/", src, re.S):
        assert "*/" not in m.group(1)[:-1] and "\\" not in m.group(1)
    assert (tmp_path / "java/com/example/pages/EscPage.java").read_bytes().decode("utf-8") == src


