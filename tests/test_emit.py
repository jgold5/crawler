def test_collisions_and_reserved_words(tmp_path):
    rs = [R(page="P", name="saveButton", xpath="//a"), R(page="P", name="save_button", xpath="//b"),
          R(page="P", name="save-button", xpath="//c"), R(page="P", name="class", xpath="//d"),
          R(page="P", name="new", xpath="//e")]
    up = page_src(gen(tmp_path / "u", rs), "PPage")
    for ident in ("SAVE_BUTTON", "SAVE_BUTTON_2", "SAVE_BUTTON_3", "CLASS", "NEW"):
        assert f"By {ident} = " in up
    cm = page_src(gen(tmp_path / "c", list(reversed(rs)), locator_style="by_methods"), "PPage")
    for ident in ("saveButton", "saveButton2", "saveButton3", "class_", "new_"):
        assert f"public By {ident}()" in cm
    # assignment is independent of input order
    assert cm == page_src(gen(tmp_path / "c2", rs, locator_style="by_methods"), "PPage")


