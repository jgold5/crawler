# ---------------------------------------------------------------- locators.json

def test_locators_json(tmp_path):
    files = gen(tmp_path)
    doc = json.loads(files["locators.json"])
    assert doc["version"] == 1
    assert list(doc["pages"]) == ["Login", "Orders", "Settings"]
    e = doc["pages"]["Login"]["emailInput"]
    assert e["xpath"] == "//input[@name='email']" and e["strategy"] == "name" and e["score"] == 90
    assert e["fragile"] is False and e["runs_verified"] == 2 and e["kind"] == "element"
    assert "template" not in e
    assert e["java"] == {"class": "com.example.pages.LoginPage", "member": "EMAIL_INPUT"}
    q = doc["pages"]["Orders"]["quantityCell"]
    assert q["template"] == {"xpath": GRID_TPL, "params": ["orderId"], "example": {"orderId": "A-100"}}
    s = doc["pages"]["Settings"]["saveButton"]
    assert s["fallbacks"] == [{"xpath": "//form[*/h2]//button[2]", "strategy": "anchored", "score": 30.5}]
    assert s["notes"] == ["positional index [2]"] and s["fragile"] is True
    assert doc["pages"]["Login"]["passwordInput"]["sources"] == ["login.feature:4", "login.feature:5"]
    assert files["locators.json"] == json.dumps(doc, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


