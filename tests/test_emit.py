def test_support_files_copied_with_package(tmp_path, monkeypatch):
    sup = tmp_path / "support"
    sup.mkdir()
    (sup / "AgGrid.java").write_text("package __PACKAGE__;\n\npublic final class AgGrid {}\n")
    (sup / "Other.java").write_text("public class Other {}")
    monkeypatch.setattr(jv, "SUPPORT_DIR", sup)
    files = gen(tmp_path / "out", helper_package="com.example.helpers")
    ag = files["java/com/example/helpers/AgGrid.java"]
    assert "package com.example.helpers;" in ag and "__PACKAGE__" not in ag
    assert ag.startswith("// Generated by crawler.")
    assert files["java/com/example/helpers/Other.java"].count("package com.example.helpers;") == 1


def test_support_dir_absent(tmp_path, monkeypatch):
    monkeypatch.setattr(jv, "SUPPORT_DIR", tmp_path / "nope")
    files = gen(tmp_path / "out")
    assert [k for k in files if k.endswith(".java")] == [
        "java/com/example/pages/LoginPage.java", "java/com/example/pages/OrdersPage.java",
        "java/com/example/pages/SettingsPage.java", "java/com/example/pages/XPathLiteral.java"]


