"""report.md: summary, "Needs attention" (fragile / under-verified with concrete suggestions), per-page tables."""
from __future__ import annotations

import re
import statistics
from collections import Counter

from crawler.config import SiteConfig
from crawler.model import LocatorResult

from .java import fmt_score

_LIT = r"""('[^']*'|"[^"]*")"""
_LABEL_PATTERNS = [
    rf"@aria-label\s*=\s*{_LIT}",
    rf"normalize-space\(\s*\.?\s*\)\s*=\s*{_LIT}",
    rf"text\(\)\s*=\s*{_LIT}",
    rf"(?<![\w@-])\.\s*=\s*{_LIT}",
    rf"contains\(\s*(?:normalize-space\(\s*\.?\s*\)|text\(\)|\.)\s*,\s*{_LIT}",
    rf"@placeholder\s*=\s*{_LIT}",
    rf"@title\s*=\s*{_LIT}",
    rf"@value\s*=\s*{_LIT}",
    rf"@name\s*=\s*{_LIT}",
]


def split_steps(xpath: str) -> list[str]:
    """Split an XPath into location steps on top-level '/' (outside quotes, brackets, parens)."""
    steps, buf, depth, quote = [], [], 0, None
    for ch in xpath:
        if quote:
            buf.append(ch)
            if ch == quote:
                quote = None
            continue
        if ch in "'\"":
            quote = ch
        elif ch in "[(":
            depth += 1
        elif ch in "])":
            depth -= 1
        elif ch == "/" and depth == 0:
            if buf:
                steps.append("".join(buf))
            buf = []
            continue
        buf.append(ch)
    if buf:
        steps.append("".join(buf))
    return steps


def _label(step: str) -> str | None:
    for pat in _LABEL_PATTERNS:
        m = re.search(pat, step)
        if m:
            return m.group(1)[1:-1]
    return None


def _tag_of(step: str) -> str:
    m = re.match(r"\s*(?:[\w-]+::)?([\w*-]+)", step)
    return m.group(1) if m else "*"


def _section(steps: list[str]) -> str | None:
    for step in reversed(steps[:-1]):
        lits = re.findall(_LIT, step)
        if lits:
            return lits[-1][1:-1]
    return None


def suggestion(r: LocatorResult, cfg: SiteConfig) -> str:
    """A concrete, human-actionable fix for a fragile locator (Markdown)."""
    attr = cfg.test_id_attrs[0] if cfg.test_id_attrs else "data-testid"
    if r.kind == "grid-cell" or r.template is not None:
        return ("ask devs to give the grid stable row ids (AG Grid `getRowId`) and a stable `col-id` "
                f"for this column, or add `{attr}` to the grid root")
    steps = split_steps(r.xpath) or [r.xpath]
    tag = r.tag or _tag_of(steps[-1])
    label = _label(steps[-1])
    section = _section(steps)
    what = f"the {_code(f'<{tag}>', table=False)}"
    what += f" '{_md(label)}'" if label else f" used as {_code(r.name, table=False)}"
    if section:
        what += f" in section '{_md(section)}'"
    return f"ask devs to add {_code(attr, table=False)} to {what} on page {_md(r.page)}"


_MD_SPECIAL = re.compile(r"([\\`*_\[\]<>|#])")


def _md(s: str) -> str:
    """Plain text -> Markdown-safe inline text (no accidental HTML, emphasis, links or table breaks)."""
    return _MD_SPECIAL.sub(r"\\\1", s.replace("\r", " ").replace("\n", " "))


def _code(s: str, table: bool = True) -> str:
    s = s.replace("\n", " ").replace("\r", " ")
    if table:
        s = s.replace("|", "\\|")
    fence = "``" if "`" in s else "`"
    pad = " " if fence == "``" else ""
    return f"{fence}{pad}{s}{pad}{fence}"


def _key(r: LocatorResult):
    return (r.page, r.name, r.xpath, r.strategy)


def render_report(results: list[LocatorResult], cfg: SiteConfig) -> str:
    rs = sorted(results, key=_key)
    total = len(rs)
    fragile = [r for r in rs if r.fragile]
    unverified = [r for r in rs if r.runs_verified <= 0]
    single = [r for r in rs if r.runs_verified == 1]
    templates = [r for r in rs if r.template is not None]
    lengths = [len(r.xpath) for r in rs]
    median = fmt_score(statistics.median(lengths)) if lengths else "n/a"
    hist = sorted(Counter(r.strategy for r in rs).items(), key=lambda kv: (-kv[1], kv[0]))

    out = [
        "<!-- Generated by crawler. DO NOT EDIT BY HAND. Regenerate with `crawler run`. -->",
        "# Locator report",
        "",
        "## Summary",
        "",
        "| Metric | Value |",
        "|---|---|",
        f"| Locators | {total} |",
        f"| Pages | {len({r.page for r in rs})} |",
        f"| Fragile | {len(fragile)} |",
        f"| Unverified (0 runs) | {len(unverified)} |",
        f"| Single-run only | {len(single)} |",
        f"| Grid templates | {len(templates)} |",
        f"| Median XPath length | {median} |",
        "",
        "### Strategies",
        "",
        "| Strategy | Count |",
        "|---|---|",
    ]
    out += [f"| {_md(k)} | {v} |" for k, v in hist] or ["| (none) | 0 |"]
    out += ["", "## Needs attention", ""]
    under = [r for r in rs if r.runs_verified < 2]
    if not fragile and not under:
        out.append("Nothing. Every locator is stable and verified in at least 2 runs.")
    if fragile:
        out += ["### Fragile locators", ""]
        for r in fragile:
            reason = "; ".join(r.notes) if r.notes else "no reason recorded"
            out.append(f"- **{_md(r.page)}.{_md(r.name)}** ({_md(r.strategy)}, score {fmt_score(r.score)}): {_code(r.xpath, table=False)}")
            out.append(f"  - Reason: {_md(reason)}")
            out.append(f"  - Suggestion: {suggestion(r, cfg)}")
        out.append("")
    if under:
        out += ["### Not verified in 2+ sessions", ""]
        for r in under:
            out.append(f"- **{_md(r.page)}.{_md(r.name)}**: verified in {r.runs_verified} run(s). "
                       "Re-run the crawl; if it keeps failing in a fresh session, the locator is not stable.")
        out.append("")

    out += ["## Pages", ""]
    by_page: dict[str, list[LocatorResult]] = {}
    for r in rs:
        by_page.setdefault(r.page, []).append(r)
    for page in sorted(by_page):
        out += [f"### {_md(page)}", "", "| Name | XPath | Strategy | Score |", "|---|---|---|---|"]
        for r in by_page[page]:
            name = r.name
            xp = r.xpath
            if r.template is not None:
                name += "(" + ", ".join(r.template.params) + ")"
                xp = r.template.xpath
            flag = " (fragile)" if r.fragile else ""
            out.append(f"| {_md(name)}{flag} | {_code(xp)} | {_md(r.strategy)} | {fmt_score(r.score)} |")
        out.append("")
    while out and out[-1] == "":
        out.pop()
    return "\n".join(out) + "\n"
